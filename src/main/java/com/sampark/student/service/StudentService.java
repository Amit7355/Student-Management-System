package com.sampark.student.service;
import java.util.List;
import org.springframework.stereotype.Service;

import com.sampark.student.model.Student;
import com.sampark.student.model.StudentDetails;
import com.sampark.student.model.StudentRequest;
import com.sampark.student.repository.StudentDetailsRepository;
import com.sampark.student.repository.StudentRepository;

import jakarta.transaction.Transactional;


    @Service
    public class StudentService {

        private StudentRepository studentRepo;
        private StudentDetailsRepository studentDetailsRepo;

        public StudentService(
                StudentRepository studentRepo,
                StudentDetailsRepository studentDetailsRepo) {

            this.studentRepo = studentRepo;
            this.studentDetailsRepo = studentDetailsRepo;
        }
        // roll generated by course  simply randomly
        public  String rollGenereateByCourse(String course)
        {
        	List<Student> li=studentRepo.getAllStudents();
        	
        	//String course1=course;
        	String roll=course+String.format("%03d", li.size()+1);
        	
        	return roll;	
        	
        }
        // roll generated  by course based on subject
        public String rollGenByCourse(String course)
        {
        	int count=studentDetailsRepo.countByCourse(course);
        	String roll=course+String.format("%03d",count+1);
        	return roll;
        }

        @Transactional
        public String saveStudent(StudentRequest request) {

            // Get course
            String course = request.getCourse().toUpperCase();
            String roll=rollGenByCourse(course);

            // Save StudentDetails
            studentDetailsRepo.saveStudentDetails(
                    roll,
                    request.getAddress(),
                    request.getEmail(),
                    request.getMobile(),
                    request.getFees(),
                    course);

            // Save Student
            studentRepo.saveStudent(
                    request.getName(),
                    roll,
                    request.getClassName(),
                    request.isStatus() );
          //  }

            return "Data inserted successfully. Roll: " + roll; 
        }
    

	public Student getStudentById(int id) 
	{
		
		return studentRepo.getStudentById(id);
	}

	@Transactional
	public String deleteStudentById(int id) {
		Student student=studentRepo.getStudentById(id);
		if(student==null)
		{
			return "no record found";
		}
		//First Deleted
		studentRepo.deleteStudentById(id);
		
		String detailsId=student.getStudentDetails().getRoll();
		
		//Second Deleted (due to foreign references)
		studentDetailsRepo.deleteStudentDetailsRoll(detailsId);
		
		return "Successfully Deleted";
	}

	@Transactional
	public String updateStudent(int id,StudentRequest studentRequest)
	{
		//before updating data you must check that element is present or not
		Student student=studentRepo.getStudentById(id); // This is used for  check that data is present or not
				if(student==null)
				{
					return "record not found";
				}
				
				String roll=student.getStudentDetails().getRoll(); // if we not use this if any different roll number you give foreign key reference error come
		        // we  not  direct store roll=studentRequest.getRoll(); but it give you  student details  roll if both  are different you not properly managed or sequence not printed
				studentDetailsRepo.updateStudentDetails(
				roll,
    		    studentRequest.getAddress(),
    		    studentRequest.getEmail(),
    		    studentRequest.getMobile(),
    		    studentRequest.getFees(),
    		    studentRequest.getCourse());
		
		        studentRepo.updateStudent(id,
				                 studentRequest.getName(),
				                 roll,
				                 studentRequest.getClassName(),
				                 studentRequest.isStatus());
		
		return "Updated Successfully";
	}

	@Transactional
	public String updatePartialStudent(String roll, int fees) {
		StudentDetails  studentDetails=studentDetailsRepo.getStudentDetailsByRoll(roll);
		if(studentDetails==null)
		{
			return "record not found";
		}
		studentDetailsRepo.updatePartialStudentDetails(roll,fees);
		return "Partial resources Updated";
	}

	@Transactional
	public String deleteSoftly(int id, boolean status) {
		
		Student student=studentRepo.getStudentById(id);
		if(student==null)
		{
			return  "record not found";
		}
		studentRepo.deleteSoftly(id,status);
		
		if(status)
		{
			return "is Active";
		}
		else 
		{
		return "DeleteSoftly if not Active";
		}
	}

	@Transactional
	public String updateAllStudentTogether( List<StudentRequest> studentRequest) {
		
		for(StudentRequest studentRequestAll: studentRequest)
		{
			studentDetailsRepo.updateStudentDetails(
			studentRequestAll.getRoll(),
		    studentRequestAll.getAddress(),
		    studentRequestAll.getEmail(),
		    studentRequestAll.getMobile(),
		    studentRequestAll.getFees(),
		    studentRequestAll.getCourse());
			
			
			studentRepo.updateStudent(studentRequestAll.getId(),
					             studentRequestAll.getName(),
				                 studentRequestAll.getRoll(),
				                 studentRequestAll.getClassName(),
				                 studentRequestAll.isStatus());
		}
		return "All Data Updated succesfully";
	}

	public List<Student> getAllStudents() {
		
		return studentRepo.getAllStudents();
	}
}

